import { describe, expect, it } from 'vitest'
import type { DbColumn, DbTable } from '../db/model'
import { tableMigration } from './table-migration'

const column = (name: string, formatted: string, extra: Partial<DbColumn> = {}): DbColumn => ({
  name,
  position: 1,
  typeName: formatted,
  formatted,
  isEnum: false,
  enumValues: [],
  notNull: false,
  identity: false,
  identityAlways: false,
  generated: false,
  ...extra,
})

const notes: DbTable = {
  schema: 'user_tables',
  name: 'notes',
  kind: 'table',
  columns: [column('id', 'bigint', { notNull: true, identity: true, identityAlways: true }), column('title', 'text'), column('price', 'numeric(12,2)')],
  foreignKeys: [],
  indexes: [],
  checks: [],
}

const ddl = {
  constraints: [{ name: 'notes_pkey', definition: 'PRIMARY KEY (id)' }],
  indexes: ['CREATE INDEX notes_title_idx ON user_tables.notes USING btree (title)', 'CREATE INDEX notes_title_idx1 ON user_tables.notes USING gin (title gin_trgm_ops)'],
}

describe('tableMigration', () => {
  it('makes the table with its columns, key and indexes as the catalogue has them, each only where it is missing', () => {
    expect(tableMigration(notes, ddl)).toEqual([
      'create schema if not exists "user_tables";',
      'create extension if not exists pg_trgm;',
      'create table if not exists "user_tables"."notes" (\n  "id" bigint generated always as identity,\n  "title" text,\n  "price" numeric(12,2),\n  constraint "notes_pkey" PRIMARY KEY (id)\n);',
      'create index if not exists notes_title_idx on user_tables.notes USING btree (title);',
      'create index if not exists notes_title_idx1 on user_tables.notes USING gin (title gin_trgm_ops);',
    ])
  })

  it('keeps a default, NOT NULL and a unique index, and needs pg_trgm only for a trigram index', () => {
    const table = { ...notes, columns: [column('id', 'bigint', { notNull: true, identity: true }), column('done', 'boolean', { notNull: true, defaultExpr: 'false' })] }
    const statements = tableMigration(table, { constraints: [], indexes: ['CREATE UNIQUE INDEX notes_done_key ON user_tables.notes USING btree (done)'] })
    expect(statements).toContain('create table if not exists "user_tables"."notes" (\n  "id" bigint generated by default as identity,\n  "done" boolean default false not null\n);')
    expect(statements).toContain('create unique index if not exists notes_done_key on user_tables.notes USING btree (done);')
    expect(statements).not.toContain('create extension if not exists pg_trgm;')
  })

  it('keeps a quoted index name whole, spaces and quotes included', () => {
    const statements = tableMigration(notes, { constraints: [], indexes: ['CREATE INDEX "My ""Title"" idx" ON user_tables.notes USING btree (title)'] })
    expect(statements).toContain('create index if not exists "My ""Title"" idx" on user_tables.notes USING btree (title);')
  })

  it('refuses a generated column, which a table users add never has', () => {
    const table = { ...notes, columns: [column('total', 'numeric', { generated: true, defaultExpr: 'price * 2' })] }
    expect(() => tableMigration(table, ddl)).toThrow('user_tables.notes.total is a generated column')
  })
})
