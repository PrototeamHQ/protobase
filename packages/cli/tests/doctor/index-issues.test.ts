import { Kysely } from 'kysely'
import { PGliteDialect } from 'kysely-pglite-dialect'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { tableIndexes } from '@protobase/query'
import { createAdmin } from '@protobase/server'
import { agencies } from '../../../../examples/property-portal/config/agencies/data'
import { agenciesView } from '../../../../examples/property-portal/config/agencies/ui'
import { places } from '../../../../examples/property-portal/config/places/data'
import { placesView } from '../../../../examples/property-portal/config/places/ui'
import { createTrigramPg } from '../../../../test-support/pglite-snapshot'
import { as, testAuthenticator } from '../../../../test-support/server'
import { indexIssues } from '../../src/doctor/index-issues'
import { readShapes } from '../../src/doctor/read-shapes'

// property-finder's places and agencies as they were when the scan guard came: their list pages sort by name and count
// regions, which only pg_trgm indexes and a (country, region) index served, so the API refused both pages.
const schema = `
  create schema market;
  create table market.places (
    id integer generated by default as identity primary key, name text not null, region text not null,
    country text not null, latitude numeric(8, 6) not null, longitude numeric(9, 6) not null, unique (country, name)
  );
  create index places_region_idx on market.places (country, region);
  create index places_name_trgm_idx on market.places using gin (name gin_trgm_ops);
  create table market.agencies (
    id integer generated by default as identity primary key, name text not null, place_id integer not null references market.places (id),
    phone text not null, email text not null, website text not null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
  );
  create index agencies_place_idx on market.agencies (place_id);
  create index agencies_name_trgm_idx on market.agencies using gin (name gin_trgm_ops);
`

// What the app added to have them served, as its examples' 011_filter_indexes.sql does.
const fix = `
  create index places_region_only_idx on market.places (region);
  create index places_name_idx on market.places (name);
  create index places_region_trgm_idx on market.places using gin (region gin_trgm_ops);
  create index agencies_name_idx on market.agencies (name);
  create index agencies_created_at_idx on market.agencies (created_at);
`

const models = [places.toModel(), agencies.toModel()]
const shapes = readShapes({ models, views: [placesView.toModel(), agenciesView.toModel()], pages: [] })

let pg: Awaited<ReturnType<typeof createTrigramPg>>
let db: Kysely<any>
beforeAll(async () => {
  pg = await createTrigramPg()
  await pg.exec(schema)
  db = new Kysely<any>({ dialect: new PGliteDialect(pg) })
})
// Destroying the Kysely instance closes the PGlite under it.
afterAll(() => db.destroy())

const issues = async () => (await Promise.all(models.map(async (model) => indexIssues(model, await tableIndexes(db, model), shapes)))).flat()
const admin = () => createAdmin({ resources: [places, agencies], db, authenticate: testAuthenticator })
const status = async (path: string) => (await admin().request(`/api/v1/${path}`, { headers: as(undefined) })).status

describe('doctor on the places and agencies of property-finder', () => {
  it('fails each index their list pages need, naming the reads and the index to add', async () => {
    const found = await issues()
    expect(found.map((issue) => `${issue.resource}: ${issue.suggestion}`)).toEqual([
      'places: create index on "market"."places" ("name");',
      'places: create index on "market"."places" ("region");',
      'places: create index on "market"."places" using gin ("region" gin_trgm_ops);',
      'agencies: create index on "market"."agencies" ("name");',
      'agencies: create index on "market"."agencies" ("created_at");',
    ])
    expect(found.every((issue) => issue.severity === 'error')).toBe(true)
    expect(found[0]!.message).toBe(
      [
        'no index serves the column "name", so the API refuses:',
        `            GET /places?order_by=name asc ("name" is sortable; the places list's order)`,
      ].join('\n'),
    )
    expect(found[1]!.message).toContain("GET /places:facets?field=region (the places list's facets filter)")
    expect(found[3]!.message).toContain(`GET /agencies?order_by=name asc ("name" is sortable; the agencies list's order)`)
  })

  it('names what the scan guard refuses', async () => {
    expect(await status('agencies?order_by=name%20asc')).toBe(400)
    expect(await status('places?order_by=name%20asc')).toBe(400)
    expect(await status('places:facets?field=region')).toBe(400)
    expect(await status('places:facets?field=country')).toBe(200)
    expect(await status('agencies:facets?field=place_id')).toBe(200)
  })

  it('passes once the indexes are there, as the scan guard does', async () => {
    await pg.exec(fix)
    expect(await issues()).toEqual([])
    expect(await status('agencies?order_by=name%20asc')).toBe(200)
    expect(await status('places?order_by=name%20asc')).toBe(200)
    expect(await status('places:facets?field=region')).toBe(200)
  })
})
