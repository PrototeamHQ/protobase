-- A small Supabase app, as its developer would write it in the SQL editor (role postgres).
create extension if not exists pg_trgm with schema extensions;
create extension if not exists pg_cron;
create extension if not exists pg_net;

create type public.priority as enum ('low', 'normal', 'high');

create table public.profiles (id uuid primary key references auth.users(id) on delete cascade, full_name text, avatar_url text);
alter table public.profiles enable row level security;
create policy "Profiles are viewable by everyone" on public.profiles for select using (true);
create policy "Users update own profile" on public.profiles for update using ((select auth.uid()) = id);
create function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin insert into public.profiles (id, full_name) values (new.id, new.raw_user_meta_data->>'full_name'); return new; end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create table public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id),
  title text not null,
  priority public.priority,
  done boolean not null default false,
  title_length integer generated always as (length(title)) stored,
  inserted_at timestamptz not null default now()
);
create index todos_title_trgm on public.todos using gin (title extensions.gin_trgm_ops);
alter table public.todos enable row level security;
create policy "own todos" on public.todos for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create function public.todo_count() returns bigint language sql security definer set search_path = '' as $$ select count(*) from public.todos where user_id = auth.uid() $$;
grant execute on function public.todo_count() to authenticated;
create view public.open_todos with (security_invoker = true) as select id, title from public.todos where not done;

-- A webhook the app wrote itself with pg_net.
create function public.notify_done() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  perform net.http_post(url := 'https://example.com/hooks/done', body := jsonb_build_object('id', new.id));
  return new;
end $$;
create trigger on_todo_done after update of done on public.todos for each row when (new.done) execute function public.notify_done();

create schema billing;
grant usage on schema billing to authenticated;
create table billing.invoices (id bigint generated always as identity primary key, user_id uuid not null references auth.users(id), amount numeric(10, 2) not null, note text);
alter table billing.invoices enable row level security;
create policy "own invoices" on billing.invoices for select to authenticated using ((select auth.uid()) = user_id);
grant select on billing.invoices to authenticated;

insert into storage.buckets (id, name, public) values ('avatars', 'avatars', true);
create policy "Avatar images are publicly accessible" on storage.objects for select using (bucket_id = 'avatars');
create policy "Users upload own avatar" on storage.objects for insert to authenticated with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);

select cron.schedule('purge-done', '0 3 * * *', $$delete from public.todos where done and inserted_at < now() - interval '30 days'$$);
select vault.create_secret('a-webhook-token', 'webhook_token', 'The token the done webhook sends');

-- As supabase_admin, as the platform does: Realtime's publication.
do $$ begin if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then create publication supabase_realtime; end if; end $$;
alter publication supabase_realtime add table public.todos;
