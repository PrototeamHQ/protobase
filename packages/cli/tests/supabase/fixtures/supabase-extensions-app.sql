-- A Supabase app using Vault, pgmq and a Database Webhook, as its developer would make it in the dashboard and SQL editor (role postgres).
create extension if not exists pg_cron;
create extension if not exists pgmq;

create table public.orders (id bigint generated by default as identity primary key, email text not null, total numeric(10, 2) not null, inserted_at timestamptz not null default now());
alter table public.orders enable row level security;
create policy "orders are anyone's to place" on public.orders for insert to anon, authenticated with check (true);
grant insert on public.orders to anon, authenticated;
grant usage on sequence public.orders_id_seq to anon, authenticated;

-- A Database Webhook, as the dashboard creates it.
create trigger order_placed after insert on public.orders for each row
  execute function supabase_functions.http_request('http://127.0.0.1:1/hooks/order', 'POST', '{"Content-Type":"application/json"}', '{}', '5000');

-- A function reading a Vault secret, and one that queues a message.
create function public.payment_key() returns text language sql security definer set search_path = '' as $$
  select decrypted_secret from vault.decrypted_secrets where name = 'stripe_key'
$$;
revoke execute on function public.payment_key() from public, anon, authenticated;
create function public.queue_receipt() returns trigger language plpgsql security definer set search_path = '' as $$
begin perform pgmq.send('receipts', jsonb_build_object('order', new.id, 'email', new.email)); return new; end $$;
create trigger order_receipt after insert on public.orders for each row execute function public.queue_receipt();

