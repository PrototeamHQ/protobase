import { Kysely } from 'kysely'
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { defineRoles, f, resource } from '@protobase/schema'
import { createAdmin, type PipelineHook } from '../src/index'
import { signTestToken, testAuthenticator } from '../../../test-support/server'
import { openSnapshotDb, type SnapshotDb } from '../../../test-support/sql-snapshot'

const roles = defineRoles<'vms' | 'operations' | 'op_logs' | 'vm_notes' | 'transfers' | 'folders'>({
  admin: ['*'],
  member: [
    'vms.read', 'vms.update.own', 'operations.read', 'operations.create', 'operations.update', 'operations.delete',
    'op_logs.read', 'op_logs.create', 'vm_notes.read', 'vm_notes.create', 'transfers.read', 'transfers.create', 'transfers.update',
    'folders.read', 'folders.create', 'folders.update.own',
  ],
  // Reads only its own VMs, and no operation field but the kind: the VM an operation points at is hidden from it
  narrow: ['vms.read.own', 'vm_notes.read', 'vm_notes.create', { 'operations.read': ['id', 'kind'] }, { 'operations.update': ['kind'] }, 'operations.delete'],
  // Has no permission on VMs at all
  stranger: ['operations.read', 'operations.create', 'operations.update'],
})

type Vm = { locked?: boolean | null }
const vms = resource('vms')
  .table('vms')
  .fields({
    id: f.integer().readOnly().filterable(),
    tenant_id: f.integer().readOnly(),
    owner_id: f.text().readOnly().filterable(),
    name: f.text(),
    locked: f.boolean().optional(),
    deleted_at: f.timestamp().optional().readOnly(),
  })
  .primaryKey((r) => r.id)
  .tenant((r) => r.tenant_id)
  .owner((r) => r.owner_id)
  .softDelete((r) => r.deleted_at)
  // A locked VM cannot be changed by anyone; otherwise the roles decide, `.own` returning a filter checked in the database
  .access({
    update: async (ctx, record) => ((record as Vm).locked ? false : roles.can('vms.update')(ctx)),
  })

const operations = resource('operations')
  .table('operations')
  .fields({
    id: f.integer().readOnly().filterable(),
    tenant_id: f.integer().readOnly(),
    vm_id: f.relation('vms').optional().filterable(),
    kind: f.enum(['reboot', 'stop']),
    deleted_at: f.timestamp().optional().readOnly(),
  })
  .primaryKey((r) => r.id)
  .tenant((r) => r.tenant_id)
  .softDelete((r) => r.deleted_at)
  .parent((r) => r.vm_id, 'update')

// Its VM comes from a column default when a create leaves it out
const opLogs = resource('op_logs')
  .table('op_logs')
  .fields({ id: f.integer().readOnly(), vm_id: f.relation('vms').dbDefault(), body: f.text() })
  .primaryKey((r) => r.id)
  .parent((r) => r.vm_id, 'update')

const vmNotes = resource('vm_notes')
  .table('vm_notes')
  .fields({ id: f.integer().readOnly(), vm_id: f.relation('vms'), body: f.text() })
  .primaryKey((r) => r.id)
  .parent((r) => r.vm_id, 'read')

const transfers = resource('transfers')
  .table('transfers')
  .fields({ id: f.integer().readOnly(), source_vm_id: f.relation('vms'), target_vm_id: f.relation('vms') })
  .primaryKey((r) => r.id)
  .parent((r) => r.source_vm_id, 'read')
  .parent((r) => r.target_vm_id, 'update')

const folders = resource('folders')
  .table('folders')
  .fields({ id: f.integer().filterable(), owner_id: f.text().readOnly().filterable(), parent_id: f.relation('folders').optional(), name: f.text() })
  .primaryKey((r) => r.id)
  .owner((r) => r.owner_id)
  .parent((r) => r.parent_id, 'update')

const written: string[] = []
const hook: PipelineHook = async (event) => { written.push(`${event.resource.name}.${event.operation}`) }

let pg: SnapshotDb
let db: Kysely<any>
let app: ReturnType<typeof createAdmin>
beforeAll(async () => {
  pg = await openSnapshotDb('empty')
  await pg.exec(`
    create table vms (id integer generated by default as identity primary key, tenant_id integer not null, owner_id text, name text not null, locked boolean, deleted_at timestamptz);
    create table operations (id integer generated by default as identity primary key, tenant_id integer not null, vm_id integer references vms, kind text not null, deleted_at timestamptz);
    create table op_logs (id integer generated always as identity primary key, vm_id integer not null default 2 references vms, body text not null);
    create table vm_notes (id integer generated always as identity primary key, vm_id integer not null references vms, body text not null);
    create table transfers (id integer generated always as identity primary key, source_vm_id integer not null references vms, target_vm_id integer not null references vms);
    create table folders (id integer primary key, owner_id text, parent_id integer references folders, name text not null);
    insert into vms (id, tenant_id, owner_id, name, locked, deleted_at) values
      (1, 1, 'alice', 'alice one', null, null), (2, 1, 'bob', 'bob two', null, null), (3, 1, 'alice', 'alice gone', null, '2026-07-01'),
      (4, 1, 'alice', 'alice locked', true, null), (5, 2, 'alice', 'alice elsewhere', null, null);
    insert into operations (id, tenant_id, vm_id, kind, deleted_at) values
      (1, 1, 1, 'reboot', null), (2, 1, 2, 'reboot', null), (3, 2, 5, 'reboot', null), (4, 1, 2, 'stop', '2026-07-01'),
      (5, 1, 3, 'stop', '2026-07-01'), (6, 1, null, 'stop', null);
    alter table operations alter column id restart with 100;
    alter table vms alter column id restart with 100;
    insert into folders (id, owner_id, parent_id, name) values (1, 'alice', null, 'alice root'), (2, 'bob', null, 'bob root');
    update folders set parent_id = 2 where id = 1;
    insert into folders (id, owner_id, parent_id, name) values (3, 'alice', null, 'three'), (4, 'alice', 3, 'four'), (5, 'alice', null, 'five'), (6, 'alice', 5, 'six');
    update folders set parent_id = 4 where id = 3;
  `)
  db = new Kysely({ dialect: pg.dialect })
  app = createAdmin({ resources: [vms, operations, opLogs, vmNotes, transfers, folders], db, authenticate: testAuthenticator, options: { roles, writeHooks: [hook] } })
})
afterAll(async () => { await db.destroy() })
beforeEach(() => { written.length = 0 })

const headers = (sub: string, role = 'member', tenant = 1) => ({ authorization: `Bearer ${signTestToken({ sub, roles: [role], tenant })}`, 'content-type': 'application/json' })
const send = (method: string, path: string, sub: string, body?: unknown, role?: string, tenant?: number) =>
  app.request(`/api/v1${path}`, { method, headers: { ...headers(sub, role, tenant), ...(method !== 'POST' && { 'if-match': '*' }) }, ...(body !== undefined && { body: JSON.stringify(body) }) })
const batch = (ops: unknown[], sub: string, role?: string) => send('POST', ':batchWrite', sub, { ops }, role)
const rows = async (sql: string) => (await pg.query(sql)).rows

const refusal = (operation: string, name = 'operations') => ({ status: 403, type: 'urn:protobase:problem:access-denied', detail: `You may not ${operation} this ${name} record` })
const expectRefused = async (response: Response, operation: string, name?: string) => {
  expect(response.status).toBe(403)
  expect(await response.json()).toMatchObject(refusal(operation, name))
}

describe('creating a record under a parent', () => {
  it('needs update on the VM: the owner creates, anyone else gets the answer a refused create gets, never a 409', async () => {
    expect((await send('POST', '/operations', 'alice', { vm_id: 1, kind: 'reboot' })).status).toBe(201)
    // Bob's VM, a missing one, a soft-deleted one, a locked one, and alice's VM of another tenant
    for (const vm_id of [2, 999, 3, 4, 5]) await expectRefused(await send('POST', '/operations', 'alice', { vm_id, kind: 'stop' }), 'create')
    // A caller with no permission on VMs at all gets the same answer
    for (const vm_id of [1, 999]) await expectRefused(await send('POST', '/operations', 'carol', { vm_id, kind: 'stop' }, 'stranger'), 'create')
    expect(await rows('select vm_id, kind from operations where id >= 100 order by id')).toEqual([{ vm_id: 1, kind: 'reboot' }])
  })

  it('checks a parent a column default sets, from the record as written, and calls no hook', async () => {
    await expectRefused(await send('POST', '/op_logs', 'alice', { body: 'on the default VM' }), 'create', 'op_logs')
    expect(await rows('select 1 from op_logs')).toEqual([])
    expect(written).toEqual([])
    expect((await send('POST', '/op_logs', 'bob', { body: 'bob may' })).status).toBe(201)
    expect(written).toEqual(['op_logs.create'])
  })

  it('takes no shared verdict from an earlier write of another caller', async () => {
    expect((await send('POST', '/operations', 'bob', { vm_id: 2, kind: 'stop' })).status).toBe(201)
    await expectRefused(await send('POST', '/operations', 'alice', { vm_id: 2, kind: 'stop' }), 'create')
    await expectRefused(await send('POST', '/operations', 'bob', { vm_id: 1, kind: 'stop' }), 'create')
    expect((await send('POST', '/operations', 'alice', { vm_id: 1, kind: 'stop' })).status).toBe(201)
  })

  it('with a read need, only needs to see the VM', async () => {
    expect((await send('POST', '/vm_notes', 'alice', { vm_id: 2, body: 'seen' })).status).toBe(201)
    // Outside the read row filter of a caller who reads only their own VMs
    await expectRefused(await send('POST', '/vm_notes', 'alice', { vm_id: 2, body: 'unseen' }, 'narrow'), 'create', 'vm_notes')
    expect((await send('POST', '/vm_notes', 'alice', { vm_id: 1, body: 'own' }, 'narrow')).status).toBe(201)
    expect(await rows('select vm_id, body from vm_notes order by id')).toEqual([{ vm_id: 2, body: 'seen' }, { vm_id: 1, body: 'own' }])
  })

  it('checks each parent with its own need, also when both point at one VM', async () => {
    await expectRefused(await send('POST', '/transfers', 'bob', { source_vm_id: 1, target_vm_id: 1 }), 'create', 'transfers')
    const created = await send('POST', '/transfers', 'bob', { source_vm_id: 1, target_vm_id: 2 })
    expect(created.status).toBe(201)
    const { id } = await created.json()
    await expectRefused(await send('PATCH', `/transfers/${id}`, 'bob', { source_vm_id: 2, target_vm_id: 1 }), 'update', 'transfers')
    expect(await rows(`select source_vm_id, target_vm_id from transfers where id = ${id}`)).toEqual([{ source_vm_id: 1, target_vm_id: 2 }])
  })
})

describe('changing and deleting a record under a parent', () => {
  it('cannot move a record onto a VM the caller may not update, nor off one, nor clear its VM', async () => {
    await expectRefused(await send('PATCH', '/operations/1', 'alice', { vm_id: 2 }), 'update')
    await expectRefused(await send('PATCH', '/operations/2', 'alice', { vm_id: 1 }), 'update')
    await expectRefused(await send('PATCH', '/operations/2', 'alice', { vm_id: null }), 'update')
    await expectRefused(await send('PATCH', '/operations/6', 'alice', { vm_id: 2 }), 'update')
    // Alice's operation of another tenant onto her VM of this one: that VM does not exist in her tenant
    await expectRefused(await send('PATCH', '/operations/3', 'alice', { vm_id: 1 }, 'member', 2), 'update')
    expect(await rows('select id, vm_id from operations where id in (1, 2, 3, 6) order by id')).toEqual([{ id: 1, vm_id: 1 }, { id: 2, vm_id: 2 }, { id: 3, vm_id: 5 }, { id: 6, vm_id: null }])
    expect(written).toEqual([])
  })

  it('checks the stored VM when the caller cannot see the relation, and lets the owner change and delete', async () => {
    await expectRefused(await send('PATCH', '/operations/2', 'alice', { kind: 'stop' }, 'narrow'), 'update')
    await expectRefused(await send('DELETE', '/operations/2', 'alice', undefined, 'narrow'), 'delete')
    await expectRefused(await send('DELETE', '/operations/2', 'alice'), 'delete')
    expect(await rows('select kind, deleted_at from operations where id = 2')).toEqual([{ kind: 'reboot', deleted_at: null }])
    expect((await send('PATCH', '/operations/2', 'bob', { kind: 'stop' })).status).toBe(200)
    expect((await send('DELETE', '/operations/2', 'bob')).status).toBe(204)
  })

  it('does nothing at all for an update that changes nothing', async () => {
    const before = await rows('select * from operations where id = 1')
    const statuses = []
    for (const body of [{}, { id: 7, tenant_id: 2 }]) statuses.push((await send('PATCH', '/operations/1', 'bob', body)).status)
    expect(statuses).toEqual([200, 400])
    expect(await rows('select * from operations where id = 1')).toEqual(before)
    expect(written).toEqual([])
  })

  it('refuses to restore a record whose VM the caller may not update, or whose VM is deleted', async () => {
    for (const id of [4, 5]) await expectRefused(await send('POST', `/operations/${id}:undelete`, 'alice'), 'update')
    expect(await rows('select id from operations where id in (4, 5) and deleted_at is not null order by id')).toEqual([{ id: 4 }, { id: 5 }])
  })
})

describe('a batch under parents', () => {
  it('fails as a whole on the operation whose parent refuses', async () => {
    const [{ count: before }] = await rows('select count(*)::int as count from operations')
    const response = await batch([
      { op: 'create', resource: 'operations', data: { vm_id: 1, kind: 'reboot' } },
      { op: 'create', resource: 'operations', data: { vm_id: 2, kind: 'reboot' } },
    ], 'alice')
    expect(response.status).toBe(403)
    expect(await response.json()).toMatchObject({ operation: 1, ...refusal('create') })
    const moved = await batch([
      { op: 'create', resource: 'operations', ref: 'op', data: { vm_id: 1, kind: 'reboot' } },
      { op: 'update', resource: 'operations', key: { $ref: 'op' }, etag: '*', data: { vm_id: 2 } },
    ], 'alice')
    expect(await moved.json()).toMatchObject({ operation: 1, ...refusal('update') })
    const deleted = await batch([
      { op: 'create', resource: 'operations', data: { vm_id: 2, kind: 'reboot' } },
      { op: 'delete', resource: 'operations', key: 1 },
    ], 'bob')
    expect(await deleted.json()).toMatchObject({ operation: 1, ...refusal('delete') })
    expect(await rows('select count(*)::int as count from operations')).toEqual([{ count: before }])
    expect(await rows('select deleted_at from operations where id = 1')).toEqual([{ deleted_at: null }])
  })

  it('creates a VM and an operation on it in one batch', async () => {
    const response = await batch([
      { op: 'create', resource: 'vms', ref: 'vm', data: { name: 'fresh' } },
      { op: 'create', resource: 'operations', data: { vm_id: { $ref: 'vm' }, kind: 'reboot' } },
    ], 'alice', 'admin')
    expect(response.status).toBe(200)
  })
})

describe('a parent of the same resource', () => {
  it('follows the parent\'s own parents, and refuses a record put under itself', async () => {
    // Folder 1 sits under bob's folder 2, so updating 1 needs updating 2
    await expectRefused(await send('POST', '/folders', 'alice', { id: 10, parent_id: 1, name: 'under one' }), 'create', 'folders')
    // Folders 3 and 4 are already a cycle
    await expectRefused(await send('POST', '/folders', 'alice', { id: 11, parent_id: 3, name: 'under three' }), 'create', 'folders')
    // Folder 6 sits under 5: 5 cannot go under 6, nor under itself
    await expectRefused(await send('PATCH', '/folders/5', 'alice', { parent_id: 6 }), 'update', 'folders')
    await expectRefused(await send('PATCH', '/folders/5', 'alice', { parent_id: 5 }), 'update', 'folders')
    expect((await send('POST', '/folders', 'alice', { id: 12, parent_id: 6, name: 'under six' })).status).toBe(201)
    expect(await rows('select id, parent_id from folders where id >= 5 order by id')).toEqual([{ id: 5, parent_id: null }, { id: 6, parent_id: 5 }, { id: 12, parent_id: 6 }])
  })
})

describe('what the UI is told', () => {
  it('lists every write of operations as conditional, and no update for a record of a VM the caller may not update', async () => {
    const meta = await (await app.request('/api/meta', { headers: headers('alice') })).json()
    expect(meta.permissions.operations.conditional).toEqual(['create', 'update', 'delete'])
    expect((await (await send('GET', '/operations/1', 'alice')).json()).permissions).toMatchObject({ update: true, delete: true })
    expect((await (await send('GET', '/operations/1', 'bob')).json()).permissions).toMatchObject({ update: false, delete: false })
  })
})
