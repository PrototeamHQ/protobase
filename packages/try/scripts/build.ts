// `bun run --cwd packages/try build`: out/protobase-try.zip, holding protobase-try.exe for Windows x64, and
// out/protobase-try.version, which try.ps1 compares with the copy it has. The exe carries the automations example's
// bundle and the serve runtime; Bun cross-compiles it from any host.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { appFilesSource, bundleFiles } from '../src/app-files-source'

const root = path.join(import.meta.dirname, '..')
const repository = path.join(root, '..', '..')
const example = path.join(repository, 'tests', 'apps', 'automations')
const build = path.join(root, 'build')
const out = path.join(root, 'out')
const run = (command: string, args: string[], cwd: string) => execFileSync(command, args, { cwd, stdio: 'inherit' })

rmSync(build, { recursive: true, force: true })
rmSync(out, { recursive: true, force: true })
mkdirSync(build, { recursive: true })
mkdirSync(out, { recursive: true })

run('bun', ['run', 'protobase', 'build', '--out', path.join(build, 'app')], example)
run('bun', ['run', 'protobase', 'build-serve', '--bun', '--out', path.join(build, 'protobase-serve.js')], example)
writeFileSync(path.join(build, 'app-files.ts'), appFilesSource(path.join(build, 'app'), bundleFiles(path.join(build, 'app'))))
writeFileSync(
  path.join(build, 'entry.ts'),
  `// Generated by packages/try/scripts/build.ts.\nimport { appBundle } from '../src/app-files-source'\nimport { start } from '../src/start'\n\nawait start(appBundle, () => import('./protobase-serve.js'))\n`,
)
run('bun', ['build', '--compile', '--target=bun-windows-x64', '--outfile', path.join(build, 'protobase-try.exe'), path.join(build, 'entry.ts')], root)

run('zip', ['-9', '-j', path.join(out, 'protobase-try.zip'), path.join(build, 'protobase-try.exe')], root)
// The CLI's version, which the release stamps, and the exe's hash, so any other build replaces a copy of this one.
const { version } = JSON.parse(readFileSync(path.join(repository, 'packages', 'cli', 'package.json'), 'utf8'))
const hash = createHash('sha256').update(readFileSync(path.join(build, 'protobase-try.exe'))).digest('hex').slice(0, 12)
writeFileSync(path.join(out, 'protobase-try.version'), `${version}-${hash}\n`)
console.log(`wrote ${path.relative(repository, out)}: protobase-try.zip and protobase-try.version (${version}-${hash})`)
