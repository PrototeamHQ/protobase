// The source of build/app-files.ts, which scripts/build.ts writes: one embedded-file import per file of the app bundle in
// build/app, and an id of their contents, so the compiled launcher carries the bundle and knows when the copy on disk is
// stale.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'

export const bundleFiles = (dir: string) =>
  readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'))
    .sort()

export const appFilesSource = (dir: string, files: string[]) => {
  const hash = createHash('sha256')
  for (const file of files) hash.update(file).update(readFileSync(path.join(dir, file)))
  const imports = files.map((file, i) => `import f${i} from './app/${file}' with { type: 'file' }`).join('\n')
  const entries = files.map((file, i) => `    [${JSON.stringify(file)}, f${i}],`).join('\n')
  return `// Generated by packages/try/scripts/build.ts.\n${imports}\n\nexport const appBundle = {\n  id: '${hash.digest('hex').slice(0, 16)}',\n  files: [\n${entries}\n  ] as [string, string][],\n}\n`
}
