/** The icons an action's, a field's or a sign-in prompt's `icon` may name. */
const byName: Record<string, LucideIcon> = {
  wallet: Wallet,
  'file-text': FileText,
  send: Send,
  ruler: RulerDimensionLine,
  bed: Bed,
  bath: Bath,
  house: House,
  'door-open': DoorOpen,
  'land-plot': LandPlot,
  leaf: Leaf,
  tag: Tag,
  key: KeyRound,
  calendar: Calendar,
  heart: Heart,
  bell: Bell,
  bookmark: Bookmark,
  'external-link': ExternalLink,
  ban: Ban,
  play: Play,
  stop: Square,
  power: Power,
  restart: RotateCw,
  terminal: Terminal,
  camera: Camera,
  'hard-drive': HardDrive,
  server: Server,
  network: Network,
  archive: Archive,
  copy: Copy,
  'arrow-right-left': ArrowRightLeft,
  download: Download,
  upload: Upload,
  cpu: Cpu,
  memory: MemoryStick,
  plug: Plug,
  wrench: Wrench,
}

/** The icon a name stands for, or nothing for a name the app does not know. */
export const namedIcon = (name: string | undefined): LucideIcon | undefined => (name !== undefined && Object.hasOwn(byName, name) ? byName[name] : undefined)
