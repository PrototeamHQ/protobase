create extension if not exists pg_trgm;

-- What everyone browses: the places homes are in, the agencies that list them, the listings and their photos.
create schema market;

create table market.places (
  id integer generated by default as identity primary key,
  name text not null,
  -- The province (NL) or autonomous community (ES).
  region text not null,
  country text not null check (country in ('NL', 'ES')),
  latitude numeric(8, 6) not null check (latitude between -90 and 90),
  longitude numeric(9, 6) not null check (longitude between -180 and 180),
  unique (country, name)
);

create index places_region_idx on market.places (country, region);
create index places_name_trgm_idx on market.places using gin (name gin_trgm_ops);

create table market.agencies (
  id integer generated by default as identity primary key,
  name text not null,
  place_id integer not null references market.places (id),
  phone text not null,
  email text not null,
  website text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index agencies_place_idx on market.agencies (place_id);
create index agencies_name_trgm_idx on market.agencies using gin (name gin_trgm_ops);

create type market.offer_type as enum ('sale', 'rent');
create type market.property_type as enum ('apartment', 'house', 'townhouse', 'villa', 'studio', 'penthouse');
create type market.listing_status as enum ('available', 'under_offer', 'sold', 'let');
-- Best first, so `energy_label <= 'b'` means B or better. The Dutch scale runs from A++++; the Spanish one from A.
create type market.energy_label as enum ('a_plus_4', 'a_plus_3', 'a_plus_2', 'a_plus', 'a', 'b', 'c', 'd', 'e', 'f', 'g');

create table market.listings (
  id bigint generated by default as identity primary key,
  agency_id integer not null references market.agencies (id),
  place_id integer not null references market.places (id),
  offer_type market.offer_type not null,
  property_type market.property_type not null,
  status market.listing_status not null default 'available',
  -- The street and number as the country writes them: "Keizersgracht 123-2", "Calle de Serrano, 45".
  address text not null,
  postal_code text not null,
  latitude numeric(8, 6) not null check (latitude between -90 and 90),
  longitude numeric(9, 6) not null check (longitude between -180 and 180),
  -- The asking price, or the rent per month, in euros.
  price numeric(12, 2) not null check (price > 0),
  living_area integer not null check (living_area > 0),
  price_per_m2 numeric(10, 2) generated always as (round(price / living_area, 2)) stored,
  plot_area integer check (plot_area > 0),
  rooms integer not null check (rooms > 0),
  bedrooms integer not null check (bedrooms >= 0 and bedrooms < rooms),
  bathrooms integer not null default 1 check (bathrooms >= 0),
  built_year integer check (built_year between 1500 and 2100),
  -- Null while the certificate is pending ("en trámite").
  energy_label market.energy_label,
  garden boolean not null default false,
  balcony boolean not null default false,
  parking boolean not null default false,
  description text not null,
  -- The cover photo, a file URI such as public:listings/house-03.png.
  photo text,
  -- Who to call about a viewing, shown to signed-in members.
  agent_name text not null,
  agent_phone text not null,
  -- When the listing went public; null while it is a draft.
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((status <> 'sold' or offer_type = 'sale') and (status <> 'let' or offer_type = 'rent'))
);

create index listings_published_idx on market.listings (published_at desc);
create index listings_place_idx on market.listings (place_id, offer_type, price);
create index listings_agency_idx on market.listings (agency_id, published_at desc);
create index listings_offer_idx on market.listings (offer_type, status, price);
create index listings_type_idx on market.listings (property_type, offer_type);
create index listings_area_idx on market.listings (living_area);
create index listings_rooms_idx on market.listings (rooms, bedrooms);
create index listings_energy_idx on market.listings (energy_label);
create index listings_address_trgm_idx on market.listings using gin (address gin_trgm_ops);

create table market.listing_photos (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references market.listings (id) on delete cascade,
  position integer not null check (position > 0),
  photo text not null,
  caption text,
  unique (listing_id, position)
);

create table public.seed_info (
  scale text not null,
  seeded_at timestamptz not null default now()
);
