// Writes skills/protobase/SKILL.md, the protobase agent skill, from the docs site's pages: the getting-started guides in
// full, in the sidebar's order, then one line per reference page with its Markdown URL. The docs site serves the same
// file at https://docs.protobase.net/skills/protobase/SKILL.md. With --check it writes nothing and fails when the
// committed file is not what it would write, which CI runs so the skill cannot fall behind the docs.
//
//   bun run docs:skill [--check]
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { pageMarkdown } from '../website/src/markdown/page-markdown'
import { guides, reference, startHere } from '../website/sidebar.mjs'

const root = join(import.meta.dir, '..')
const docsDir = join(root, 'website/src/content/docs')
const output = join(root, 'skills/protobase/SKILL.md')
const docsOrigin = 'https://docs.protobase.net'

interface Page {
  path: string
  title: string
  description: string
  markdown: string
}

async function readPage(path: string): Promise<Page> {
  const filePath = await existing(join(docsDir, `${path}.md`), join(docsDir, `${path}.mdx`))
  const text = await readFile(filePath, 'utf8')
  const match = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!match?.[1]) throw new Error(`${path} has no frontmatter`)
  const { title, description } = Bun.YAML.parse(match[1]) as { title?: string; description?: string }
  if (!title || !description) throw new Error(`${path} needs a title and a description`)
  const markdown = pageMarkdown({ title, description, body: text.slice(match[0].length), filePath })
  return { path, title, description, markdown }
}

const existing = async (...paths: string[]) => {
  for (const path of paths) if (await Bun.file(path).exists()) return path
  throw new Error(`no page at ${paths.join(' or ')}`)
}

// A page under the skill's own title: its headings one level down and its links to other pages absolute. Lines inside
// fenced blocks stay as they are.
function nested(markdown: string) {
  let fence: string | undefined
  return markdown
    .split('\n')
    .map((line) => {
      const fenceMark = line.trim().match(/^(`{3,}|~{3,})/)?.[1]
      if (fence) {
        if (fenceMark?.startsWith(fence)) fence = undefined
        return line
      }
      if (fenceMark) {
        fence = fenceMark
        return line
      }
      const heading = /^#+ /.test(line) ? `#${line}` : line
      return heading.replaceAll('](/', `](${docsOrigin}/`)
    })
    .join('\n')
}

const markdownUrl = (path: string) => `${docsOrigin}/${path}.md`

const guidePages = await Promise.all([...startHere, ...guides].map(readPage))
const referencePages = await Promise.all(reference.map(readPage))
const schemaApi = { path: 'api/schema', title: '@protobase/schema API', description: 'Every export of @protobase/schema, generated from its doc comments.' }

const skill = `---
name: protobase
description: Protobase's documentation, for building, configuring, deploying and extending a Protobase admin app on a Postgres database (data.ts, ui.ts, composed pages, API functions, plugins, themes, the protobase CLI). Use it when working in a project that depends on @protobase packages, or when asked about Protobase.
---

<!-- Generated by scripts/protobase-skill.ts from website/src/content/docs: run \`bun run docs:skill\`, do not edit. -->

# Protobase

Protobase's getting-started guides from ${docsOrigin} follow in full. They describe its latest release; a project may be on an older one, so check the versions of its \`@protobase\` packages.

${guidePages.map((page) => nested(page.markdown).trim()).join('\n\n')}

## Reference pages

For what the guides leave out, read a reference page: each is Markdown at its URL, so fetch the one you need instead of the HTML page.

${[...referencePages, schemaApi].map((page) => `- [${page.title}](${markdownUrl(page.path)}): ${page.description}`).join('\n')}
`

if (process.argv.includes('--check')) {
  const committed = await readFile(output, 'utf8').catch(() => '')
  if (committed !== skill) {
    console.error('skills/protobase/SKILL.md does not match the docs: run `bun run docs:skill` and commit it')
    process.exit(1)
  }
} else {
  await writeFile(output, skill)
  console.log(`${guidePages.length} guides and ${referencePages.length + 1} reference pages: ${skill.length} characters`)
}
