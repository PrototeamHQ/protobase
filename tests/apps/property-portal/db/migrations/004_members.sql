-- What a signed-in member keeps for themselves: search profiles with their alerts, favorites and notes. Each row names
-- its owner, a Better Auth user; the app's row filters (`.own`) show it to that user alone.
create schema members;

create type members.alert_frequency as enum ('instant', 'daily');

create table members.search_profiles (
  id bigint generated by default as identity primary key,
  user_id text not null references auth."user" (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  offer_type market.offer_type not null,
  -- Empty: anywhere. With a radius, also within that many kilometres of the place's centre.
  place_id integer references market.places (id),
  radius_km integer not null default 0 check (radius_km between 0 and 50),
  property_type market.property_type,
  min_price numeric(12, 2) check (min_price >= 0),
  max_price numeric(12, 2) check (max_price >= 0),
  min_living_area integer check (min_living_area > 0),
  min_rooms integer check (min_rooms > 0),
  -- This label or a better one.
  min_energy_label market.energy_label,
  alert_frequency members.alert_frequency not null default 'daily',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (min_price is null or max_price is null or max_price >= min_price),
  -- The alerts' owner is the profile's: they reference both.
  unique (id, user_id)
);

create index search_profiles_user_idx on members.search_profiles (user_id, created_at desc);
create index search_profiles_matching_idx on members.search_profiles (offer_type) where active;

create table members.alerts (
  id bigint generated by default as identity primary key,
  user_id text not null,
  search_profile_id bigint not null,
  listing_id bigint not null references market.listings (id) on delete cascade,
  matched_at timestamptz not null default now(),
  emailed_at timestamptz,
  seen boolean not null default false,
  foreign key (search_profile_id, user_id) references members.search_profiles (id, user_id) on delete cascade,
  unique (search_profile_id, listing_id)
);

create index alerts_user_idx on members.alerts (user_id, matched_at desc);
create index alerts_listing_idx on members.alerts (listing_id);
create index alerts_unmailed_idx on members.alerts (user_id) where emailed_at is null;

create table members.favorites (
  id bigint generated by default as identity primary key,
  user_id text not null references auth."user" (id) on delete cascade,
  listing_id bigint not null references market.listings (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, listing_id)
);

create index favorites_listing_idx on members.favorites (listing_id);
create index favorites_user_idx on members.favorites (user_id, created_at desc);

create table members.notes (
  id bigint generated by default as identity primary key,
  user_id text not null references auth."user" (id) on delete cascade,
  listing_id bigint not null references market.listings (id) on delete cascade,
  body text not null check (length(trim(body)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index notes_user_idx on members.notes (user_id, updated_at desc);
create index notes_listing_idx on members.notes (listing_id, user_id);
