-- Members save the listings page's filters as searches instead of filling in search profiles: a search is the filter
-- the page had, and whether they hear of new listings that fit it at once, in a daily digest or not at all. The
-- profiles go with their alerts, which the searches record again from the next listing published.
drop table members.alerts;
drop table members.search_profiles;
drop type members.alert_frequency;

create type members.alert_frequency as enum ('instant', 'daily', 'none');

create table members.saved_searches (
  id bigint generated by default as identity primary key,
  user_id text not null references auth."user" (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  -- The listings' filter as the listings page's address holds it (AIP-160), such as
  -- `for_sale = true AND place_id = 1 AND purchase_price >= 300000 AND purchase_price <= 500000`.
  filter text not null,
  alert_frequency members.alert_frequency not null default 'daily',
  -- When the member last opened the search's results: the listings published since are new to them.
  seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  -- The same filter is one search.
  unique (user_id, filter),
  -- The alerts' owner is the search's: they reference both.
  unique (id, user_id)
);

create index saved_searches_user_idx on members.saved_searches (user_id, created_at desc);

create table members.alerts (
  id bigint generated by default as identity primary key,
  user_id text not null,
  saved_search_id bigint not null,
  listing_id bigint not null references market.listings (id) on delete cascade,
  matched_at timestamptz not null default now(),
  emailed_at timestamptz,
  foreign key (saved_search_id, user_id) references members.saved_searches (id, user_id) on delete cascade,
  unique (saved_search_id, listing_id)
);

create index alerts_user_idx on members.alerts (user_id, matched_at desc);
create index alerts_listing_idx on members.alerts (listing_id);
create index alerts_unmailed_idx on members.alerts (user_id) where emailed_at is null;
