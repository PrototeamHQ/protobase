-- A small Supabase app that `protobase import supabase` moves with no agent step, made as its developer would in the
-- SQL editor, on Supabase Auth's and Storage's schemas and with alice and bob, users Supabase Auth itself made
-- (packages/cli/tests/supabase/fixtures/gotrue-users.sql). Each user keeps notes in lists, under row security on
-- auth.uid(); a private bucket keeps a file in each user's folder; the notes are in Realtime's publication; and only
-- alice may join the private topic room:alice.

create table public.lists (id bigint generated by default as identity primary key, name text not null);
create table public.notes (
  id bigint generated by default as identity primary key,
  owner uuid not null default auth.uid() references auth.users (id),
  list_id bigint not null references public.lists (id),
  body text not null
);
create index notes_owner on public.notes (owner);
create index notes_list_id on public.notes (list_id);

alter table public.lists enable row level security;
create policy "Signed-in users read the lists" on public.lists for select to authenticated using (true);
alter table public.notes enable row level security;
create policy "Users read own notes" on public.notes for select to authenticated using ((select auth.uid()) = owner);
create policy "Users add own notes" on public.notes for insert to authenticated with check ((select auth.uid()) = owner);

-- How many of the caller's notes a list holds, under the caller's row security.
create function public.note_count(list bigint) returns bigint language sql stable as $$
  select count(*) from public.notes where list_id = list
$$;

-- Supabase's grants on what the app makes in public.
grant usage on schema public to anon, authenticated, service_role;
grant all on all tables in schema public to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;
grant execute on all functions in schema public to anon, authenticated, service_role;

insert into public.lists (name) values ('Home'), ('Work');
insert into public.notes (owner, list_id, body) values
  ('0fd5f0e7-858d-4984-ad61-299783467157', 1, 'Alice buys milk'),
  ('0fd5f0e7-858d-4984-ad61-299783467157', 2, 'Alice ships the release'),
  ('c659ea51-aea7-4c2c-84af-61ecccf38207', 1, 'Bob fixes the bike');

-- Storage: a private bucket, each user reading and writing their own folder.
insert into storage.buckets (id, name, public) values ('notes', 'notes', false);
create policy "Users read own files" on storage.objects for select to authenticated
  using (bucket_id = 'notes' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "Users upload own files" on storage.objects for insert to authenticated
  with check (bucket_id = 'notes' and (storage.foldername(name))[1] = (select auth.uid())::text);

-- Realtime, as its service makes it on Supabase: realtime.messages, realtime.topic() and the publication, with the
-- notes in it.
create schema realtime;
grant usage on schema realtime to anon, authenticated, service_role;
create table realtime.messages (
  topic text not null,
  extension text not null,
  payload jsonb,
  event text,
  private boolean default false,
  updated_at timestamp without time zone not null default now(),
  inserted_at timestamp without time zone not null default now(),
  id uuid not null default gen_random_uuid(),
  primary key (id, inserted_at)
);
alter table realtime.messages enable row level security;
grant select, insert, update on realtime.messages to anon, authenticated, service_role;
create function realtime.topic() returns text language sql stable as $$ select nullif(current_setting('realtime.topic', true), '')::text $$;
create policy "Alice joins her room" on realtime.messages for select to authenticated
  using (realtime.topic() = 'room:alice' and (select auth.uid()) = '0fd5f0e7-858d-4984-ad61-299783467157');
create publication supabase_realtime;
alter publication supabase_realtime add table public.notes;
